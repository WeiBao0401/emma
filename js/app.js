// ---------------------------------------------------------------- service worker
// Nothing that a reload would break: no lookup running, no lesson or dictation, sheet, unsent text, pending import.
function isIdle() {
  const a = document.activeElement;
  const typing = a && /INPUT|TEXTAREA/.test(a.tagName) && a.value;
  return !busyCount && !(look && look.isBusy()) && !(lesson && lesson.inSession()) && !(dictation && dictation.inSession()) &&
    !sheetView && !typing && !words.enriching() && !(parent && parent.holding()) &&
    !(weekly && weekly.holding()) && !(capture && capture.holding()) &&   // a share sheet open, a photo not saved yet
    !(chat && (chat.inSession() || chat.holding())) &&                     // the teacher answering, a recording, a question not sent
    !(app.textread && (app.textread.inSession() || app.textread.holding())) && // 课文陪读: a photo, a page being prepared or read
    !(kidme && kidme.holding()) && !(revise && revise.inSession()) &&      // 0.7.0: “我” not saved, a review running
    !(mistakes && (mistakes.inSession() || mistakes.holding())) &&          // the teacher reading or explaining, questions not kept
    !(lib && lib.inSession && lib.inSession());                             // 单词本's 练一下
}
// Stricter, for a reload while the app is in use: nothing being read either.
const isQuiet = () => isIdle() && !(look && look.hasResult()) && !(lib && lib.inDetail());

let swReg = null;
let reloaded = false;
function reloadOnce() { if (reloaded) return; reloaded = true; location.reload(); }
function registerSW() {
  if (!('serviceWorker' in navigator)) return;
  const local = /^(localhost|127\.0\.0\.1|\[::1\])$/.test(location.hostname);
  if (!((location.protocol === 'https:' && !local) || params.has('sw'))) return;
  const hadController = !!navigator.serviceWorker.controller;
  navigator.serviceWorker.addEventListener('controllerchange', () => {
    // the very first install also fires this (clients.claim); only a real update reloads
    if (!hadController || reloaded) return;
    if (isQuiet()) reloadOnce(); else { updateReady = true; renderStatus(); }
  });
  navigator.serviceWorker.register('./sw.js', { scope: './' }).then(r => { swReg = r; }).catch(() => {});
}
// iOS resumes a Home Screen app from memory instead of reloading it: that is the "next open".
function onResumeSW() {
  if (updateReady && isIdle()) reloadOnce();
  else if (swReg) swReg.update().catch(() => {});
}

