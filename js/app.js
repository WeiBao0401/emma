// ---------------------------------------------------------------- kv: async store with a sync cache
// Everything in the kv store is read once at boot (it is small), so views can read it synchronously with peek().
const kvCache = new Map();
const kv = {
  peek: (key, fallback = undefined) => (kvCache.has(key) ? structuredClone(kvCache.get(key)) : fallback),
  async get(key, fallback = undefined) {
    if (kvCache.has(key)) return structuredClone(kvCache.get(key));
    const v = await idbStore.kvGet(key);
    if (v !== undefined) kvCache.set(key, v);
    return v === undefined ? fallback : structuredClone(v);
  },
  async set(key, value) { kvCache.set(key, structuredClone(value)); await idbStore.kvSet(key, value); },
  async delete(key) { kvCache.delete(key); await idbStore.kvDelete(key); },
  keys: (prefix = '') => [...kvCache.keys()].filter(k => k.startsWith(prefix)),
};

